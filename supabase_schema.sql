-- =====================================================================
-- RPC FUNCTIONS: DYNAMIC QUERY RUNNERS
-- =====================================================================
CREATE OR REPLACE FUNCTION exec_sql(sql_query text)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  result json;
BEGIN
  EXECUTE 'SELECT json_agg(t) FROM (' || sql_query || ') t' INTO result;
  RETURN coalesce(result, '[]'::json);
END;
$$;

CREATE OR REPLACE FUNCTION exec_mutation(sql_query text)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  EXECUTE sql_query;
  RETURN json_build_object('success', true);
END;
$$;
